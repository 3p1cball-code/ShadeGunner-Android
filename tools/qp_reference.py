"""Referenzbild: dieselben Befehle wie tests/qp_test.gd, mit echtem QPainter."""
import sys
from PyQt6.QtCore import QPointF, QRectF, Qt
from PyQt6.QtGui import (QBrush, QColor, QGuiApplication, QImage, QLinearGradient, QPainter, QPen,
                         QPolygonF, QRadialGradient)
app = QGuiApplication([])
img = QImage(640, 360, QImage.Format.Format_RGB32)
img.fill(QColor(18, 22, 38))
sub = QImage(40, 30, QImage.Format.Format_ARGB32_Premultiplied)
sub.fill(0)
q = QPainter(sub)
q.fillRect(QRectF(0, 0, 40, 30), QColor(224, 72, 150, 180))
q.fillRect(QRectF(10, 8, 20, 14), QColor(64, 210, 220))
q.end()
p = QPainter(img)
p.setRenderHint(QPainter.RenderHint.Antialiasing, False)
p.fillRect(QRectF(10, 10, 100, 50), QColor(255, 138, 44))
p.fillRect(QRectF(20.5, 70.25, 60.5, 20.5), QColor(64, 210, 220, 128))
p.setPen(Qt.PenStyle.NoPen)
p.setBrush(QBrush(QColor(122, 74, 168)))
p.drawEllipse(QRectF(130, 10, 80, 50))
p.drawEllipse(QPointF(260, 40), 20.0, 12.0)
p.setBrush(QBrush(QColor(214, 220, 226)))
p.drawPolygon(QPolygonF([QPointF(300, 10), QPointF(360, 60), QPointF(290, 55)]))
pen = QPen(QColor(255, 255, 255)); pen.setWidthF(1.0); p.setPen(pen)
p.drawLine(QPointF(10, 110), QPointF(200, 110))
p.drawLine(QPointF(10, 120), QPointF(200, 150))
pen = QPen(QColor(224, 72, 150)); pen.setWidthF(4.0); pen.setCapStyle(Qt.PenCapStyle.RoundCap); p.setPen(pen)
p.drawLine(QPointF(220, 110), QPointF(320, 150))
pen = QPen(QColor(255, 138, 44)); pen.setWidthF(3.0); p.setPen(pen)
p.drawLine(QPointF(220, 160), QPointF(320, 160))
p.setPen(Qt.PenStyle.NoPen)
g = QLinearGradient(10, 180, 210, 180); g.setColorAt(0, QColor(6, 8, 14)); g.setColorAt(0.5, QColor(64, 210, 220)); g.setColorAt(1, QColor(255, 255, 255, 0))
p.fillRect(QRectF(10, 180, 200, 30), QBrush(g))
r = QRadialGradient(300, 230, 50); r.setColorAt(0, QColor(255, 138, 44, 255)); r.setColorAt(1, QColor(255, 138, 44, 0))
p.setBrush(QBrush(r)); p.drawEllipse(QPointF(300, 230), 50.0, 50.0)
p.save(); p.translate(420, 60); p.scale(2.0, 2.0); p.rotate(20)
p.fillRect(QRectF(0, 0, 30, 15), QColor(34, 96, 104)); p.restore()
p.setCompositionMode(QPainter.CompositionMode.CompositionMode_Plus)
p.fillRect(QRectF(400, 120, 120, 60), QColor(80, 40, 120))
p.setCompositionMode(QPainter.CompositionMode.CompositionMode_SourceOver)
p.setOpacity(0.5); p.drawImage(QRectF(400, 200, 80, 60), sub); p.setOpacity(1.0)
p.drawImage(530, 200, sub)
p.drawImage(QRectF(530, 250, 40, 30), sub.mirrored(True, False))
p.setClipRect(QRectF(20, 260, 60, 40)); p.fillRect(QRectF(0, 250, 200, 100), QColor(162, 168, 180)); p.setClipping(False)
pen = QPen(QColor(255, 255, 255)); pen.setWidthF(1.0); p.setPen(pen); p.setBrush(Qt.BrushStyle.NoBrush)
p.drawRect(QRectF(100, 260, 50, 30))
p.drawPoint(QPointF(170.4, 270.6))
p.end()
img.save(sys.argv[1])
print("ref ok")
